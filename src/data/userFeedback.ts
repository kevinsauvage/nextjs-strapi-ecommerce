/**
 * Feedback strings for a locale, falling back to English for anything else.
 * Framework-free so actions, services and client components share one source.
 */
export const getUserFeedback = (locale: Locale): UserFeedback => {
  switch (locale) {
    case 'es':
      return es;
    case 'fr':
      return fr;
    default:
      return en;
  }
};
